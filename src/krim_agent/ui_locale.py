class LocaleResources(LocaleView):
    strings: dict[str, str]


def locale_resources(requested: str | None = None) -> LocaleResources:
    resolved = resolve_locale(requested)
    return LocaleResources(
        **resolved.model_dump(),
        strings={
            key: english if resolved.effective == "en-US" else key
            for key, english in TRANSLATIONS.items()
        },
    )
